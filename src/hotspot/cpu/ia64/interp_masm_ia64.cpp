// Derived from cpu/riscv/interp_masm_riscv.cpp. The register mapping is
// riscv x10 -> Rtos (r8), f10 -> Ftos (f8), xbcp/xlocals/esp/xcpool/xmethod
// -> Rbcp/Rlocals/Resp/Rcpool/Rmethod, and riscv's scratch x1N -> r2N
// (x11 -> r21 ... x17 -> r27; j_rarg registers, free inside the
// interpreter). The same mapping is used by templateTable_ia64.cpp and
// templateInterpreterGenerator_ia64.cpp, so the three files compare line for
// line with riscv's. Departures that are about IA-64 rather than renaming are
// marked "IA-64:".

// Interpreter-internal scratch (see the mapping note above).
static constexpr Register Rscratch1 = r21;   // riscv x11
static constexpr Register Rscratch2 = r22;   // riscv x12
static constexpr Register Rscratch3 = r23;   // riscv x13
static constexpr Register Rscratch4 = r24;   // riscv x14
static constexpr Register Rscratch5 = r25;   // riscv x15

void InterpreterMacroAssembler::narrow(Register result) {
  assert_different_registers(result, Rscratch1, Rscratch2);
  // Get method->_constMethod->_result_type
  get_method(Rscratch1);
  ld8(Rscratch1, Address(Rscratch1, Method::const_offset()));
  ld1(Rscratch1, Address(Rscratch1, ConstMethod::result_type_offset()));

  Label done, notBool, notByte, notChar;

  // common case first
  cmp_eq_imm(ptmp0, ptmp1, T_INT, Rscratch1);
  br_cond(done, ptmp0);

  // mask integer result to narrower return type.
  cmp_eq_imm(ptmp0, ptmp1, T_BOOLEAN, Rscratch1);
  br_cond(notBool, ptmp1);
  and_imm(result, 0x1, result);
  j(done);

  bind(notBool);
  cmp_eq_imm(ptmp0, ptmp1, T_BYTE, Rscratch1);
  br_cond(notByte, ptmp1);
  sxt1(result, result);
  j(done);

  bind(notByte);
  cmp_eq_imm(ptmp0, ptmp1, T_CHAR, Rscratch1);
  br_cond(notChar, ptmp1);
  zxt2(result, result);
  j(done);

  bind(notChar);
  sxt2(result, result);

  bind(done);
  sxt4(result, result);
}

void InterpreterMacroAssembler::jump_to_entry(address entry) {
  assert(entry != nullptr, "Entry must have been generated by now");
  far_jump(entry);
}

void InterpreterMacroAssembler::check_and_handle_popframe(Register java_thread) {
  if (JvmtiExport::can_pop_frame()) {
    Label L;
    // Initiate popframe handling only if it is not already being
    // processed. If the flag has the popframe_processing bit set,
    // it means that this code is called *during* popframe handling - we
    // don't want to reenter.
    // This method is only called just after the call into the vm in
    // call_VM_base, so the arg registers are available.
    ld4(t2, Address(Rthread, JavaThread::popframe_condition_offset()));
    tbit_z(ptmp0, ptmp1, t2, exact_log2(JavaThread::popframe_pending_bit));
    br_cond(L, ptmp0);
    tbit_nz(ptmp0, ptmp1, t2, exact_log2(JavaThread::popframe_processing_bit));
    br_cond(L, ptmp0);
    // Call Interpreter::remove_activation_preserving_args_entry() to get the
    // address of the same-named entrypoint in the generated interpreter code.
    call_VM_leaf(CAST_FROM_FN_PTR(address, Interpreter::remove_activation_preserving_args_entry));
    jr(Rret);
    bind(L);
  }
}

void InterpreterMacroAssembler::load_earlyret_value(TosState state) {
  ld8(Rscratch2, Address(Rthread, JavaThread::jvmti_thread_state_offset()));
  const Address tos_addr(Rscratch2, JvmtiThreadState::earlyret_tos_offset());
  const Address oop_addr(Rscratch2, JvmtiThreadState::earlyret_oop_offset());
  const Address val_addr(Rscratch2, JvmtiThreadState::earlyret_value_offset());
  switch (state) {
    case atos:
      ld8(Rtos, oop_addr);
      st8(oop_addr, zr);
      verify_oop(Rtos);
      break;
    case ltos:
      ld8(Rtos, val_addr);
      break;
    case btos:  // fall through
    case ztos:  // fall through
    case ctos:  // fall through
    case stos:  // fall through
    case itos:
      ld4s(Rtos, val_addr);
      break;
    case ftos:
      ldfs(Ftos, val_addr);
      break;
    case dtos:
      ldfd(Ftos, val_addr);
      break;
    case vtos:
      /* nothing to do */
      break;
    default:
      ShouldNotReachHere();
  }
  // Clean up tos value in the thread object
  mov_immediate(t2, (int)ilgl);
  st4(tos_addr, t2);
  st4(val_addr, zr);
}

void InterpreterMacroAssembler::check_and_handle_earlyret(Register java_thread) {
  if (JvmtiExport::can_force_early_return()) {
    Label L;
    ld8(t2, Address(Rthread, JavaThread::jvmti_thread_state_offset()));
    beqz(t2, L);  // if thread->jvmti_thread_state() is null then exit

    // Initiate earlyret handling only if it is not already being processed.
    // If the flag has the earlyret_processing bit set, it means that this code
    // is called *during* earlyret handling - we don't want to reenter.
    ld4(t2, Address(t2, JvmtiThreadState::earlyret_state_offset()));
    cmp4_eq_imm(ptmp0, ptmp1, JvmtiThreadState::earlyret_pending, t2);
    br_cond(L, ptmp1);

    // Call Interpreter::remove_activation_early_entry() to get the address of the
    // same-named entrypoint in the generated interpreter code.
    ld8(t2, Address(Rthread, JavaThread::jvmti_thread_state_offset()));
    ld4(t2, Address(t2, JvmtiThreadState::earlyret_tos_offset()));
    call_VM_leaf(CAST_FROM_FN_PTR(address, Interpreter::remove_activation_early_entry), t2);
    jr(Rret);
    bind(L);
  }
}

// Bytecode operands as written in the classfile: big-endian.
void InterpreterMacroAssembler::get_unsigned_2_byte_index_at_bcp(Register reg, int bcp_offset) {
  assert(bcp_offset >= 0, "bcp is still pointing to start of bytecode");
  load_unaligned_be(reg, Rbcp, bcp_offset, 2, t2);
}

// IA-64: cache indices are written back by the rewriter in native (little-
// endian) order, and sit at unaligned addresses, so they are assembled a byte
// at a time -- a misaligned ld2/ld4 would fault.
void InterpreterMacroAssembler::get_cache_index_at_bcp(Register index,
                                                       Register tmp,
                                                       int bcp_offset,
                                                       size_t index_size) {
  assert(bcp_offset > 0, "bcp is still pointing to start of bytecode");
  if (index_size == sizeof(u2)) {
    load_unaligned_le(index, Rbcp, bcp_offset, 2, tmp);
  } else if (index_size == sizeof(u4)) {
    load_unaligned_le(index, Rbcp, bcp_offset, 4, tmp);
  } else if (index_size == sizeof(u1)) {
    ld1(index, Address(Rbcp, bcp_offset));
  } else {
    ShouldNotReachHere();
  }
}

// Load object from cpool->resolved_references(index)
void InterpreterMacroAssembler::load_resolved_reference_at_index(
                                Register result, Register index, Register tmp) {
  assert_different_registers(result, index, tmp);

  get_constant_pool(result);
  // Load pointer for resolved_references[] objArray
  ld8(result, Address(result, ConstantPool::cache_offset()));
  ld8(result, Address(result, ConstantPoolCache::resolved_references_offset()));
  resolve_oop_handle(result, tmp, noreg);
  // Add in the index
  assert(!UseCompressedOops, "IA-64 milestone 1 runs without compressed oops");
  shladd(result, index, LogBytesPerHeapOop, result);
  load_heap_oop(result, Address(result, arrayOopDesc::base_offset_in_bytes(T_OBJECT)), tmp, noreg);
}

void InterpreterMacroAssembler::load_resolved_klass_at_offset(
                                Register cpool, Register index, Register klass, Register temp) {
  shladd(temp, index, LogBytesPerWord, cpool);
  ld2(temp, Address(temp, sizeof(ConstantPool)));                     // temp = resolved_klass_index
  ld8(klass, Address(cpool, ConstantPool::resolved_klasses_offset())); // klass = cpool->_resolved_klasses
  shladd(klass, temp, LogBytesPerWord, klass);
  ld8(klass, Address(klass, Array<Klass*>::base_offset_in_bytes()));
}

// Generate a subtype check: branch to ok_is_subtype if sub_klass is a
// subtype of super_klass.
//
// Args:
//      Rtos: superklass
//      Rsub_klass: subklass
//
// Kills:
//      r22 (riscv x12), r25 (riscv x15), t0, t1, ptmp0/1
void InterpreterMacroAssembler::gen_subtype_check(Register Rsub_klass,
                                                  Label& ok_is_subtype) {
  assert_different_registers(Rsub_klass, Rtos, Rscratch2, Rscratch5);

  // Profile the not-null value's klass.
  profile_typecheck(Rscratch2, Rsub_klass, Rscratch5);

  // Do the check.
  check_klass_subtype(Rsub_klass, Rtos, Rscratch2, Rscratch5, ok_is_subtype);
}

// Java Expression Stack
//
// Resp points at the top element. A pop is one post-incrementing load where
// the width allows it; a push pre-decrements with adds, since IA-64 has no
// pre-decrement addressing.

void InterpreterMacroAssembler::pop_ptr(Register r) {
  ld8_inc(r, Resp, wordSize);
}

void InterpreterMacroAssembler::pop_i(Register r) {
  // Only the low 4 bytes of an int slot are defined (JavaCallArguments
  // writes 4), so load 4 and sign-extend: registers hold ints sign-extended.
  ld4_inc(r, Resp, wordSize);
  sxt4(r, r);
}

void InterpreterMacroAssembler::pop_l(Register r) {
  ld8_inc(r, Resp, 2 * Interpreter::stackElementSize);
}

void InterpreterMacroAssembler::push_ptr(Register r) {
  adds(Resp, -wordSize, Resp);
  Assembler::st8(Resp, r);
}

void InterpreterMacroAssembler::push_i(Register r) {
  adds(Resp, -wordSize, Resp);
  sxt4(r, r);
  Assembler::st8(Resp, r);
}

void InterpreterMacroAssembler::push_l(Register r) {
  // The value goes in the lower-addressed slot; the other is zeroed, as on
  // every port.
  adds(Resp, -wordSize, Resp);
  st8_inc(Resp, zr, -wordSize);
  Assembler::st8(Resp, r);
}

void InterpreterMacroAssembler::pop_f(FloatRegister r) {
  Assembler::ldfs(r, Resp);
  adds(Resp, wordSize, Resp);
}

void InterpreterMacroAssembler::pop_d(FloatRegister r) {
  Assembler::ldfd(r, Resp);
  adds(Resp, 2 * Interpreter::stackElementSize, Resp);
}

void InterpreterMacroAssembler::push_f(FloatRegister r) {
  adds(Resp, -wordSize, Resp);
  Assembler::stfs(Resp, r);
}

void InterpreterMacroAssembler::push_d(FloatRegister r) {
  adds(Resp, -2 * wordSize, Resp);
  Assembler::stfd(Resp, r);
}

void InterpreterMacroAssembler::pop(TosState state) {
  switch (state) {
    case atos:
      pop_ptr();
      verify_oop(Rtos);
      break;
    case btos:  // fall through
    case ztos:  // fall through
    case ctos:  // fall through
    case stos:  // fall through
    case itos:
      pop_i();
      break;
    case ltos:
      pop_l();
      break;
    case ftos:
      pop_f();
      break;
    case dtos:
      pop_d();
      break;
    case vtos:
      /* nothing to do */
      break;
    default:
      ShouldNotReachHere();
  }
}

void InterpreterMacroAssembler::push(TosState state) {
  switch (state) {
    case atos:
      verify_oop(Rtos);
      push_ptr();
      break;
    case btos:  // fall through
    case ztos:  // fall through
    case ctos:  // fall through
    case stos:  // fall through
    case itos:
      push_i();
      break;
    case ltos:
      push_l();
      break;
    case ftos:
      push_f();
      break;
    case dtos:
      push_d();
      break;
    case vtos:
      /* nothing to do */
      break;
    default:
      ShouldNotReachHere();
  }
}

